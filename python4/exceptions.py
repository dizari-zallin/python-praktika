"""Пользовательские исключения системы управления грузами."""


# Общий тип ошибок предметной области. Конкретные случаи наследуются от него, чтобы ловить их по одному или все сразу.
class CargoError(Exception):
    """Базовое исключение предметной области."""


# Груз с таким номером в хранилище отсутствует.
class CargoNotFoundError(CargoError):
    """Попытка изменить или получить несуществующий груз."""


# Масса, статус или другое поле не прошло проверку.
class ValidationError(CargoError):
    """Некорректные данные груза."""


# Файл JSON или CSV не прочитался или не записался.
class StorageError(CargoError):
    """Ошибка чтения или записи файла."""
